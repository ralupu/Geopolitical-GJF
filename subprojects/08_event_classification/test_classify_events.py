# 5. Localized classification constraints
# ===========================================================================
class TestLocalizedConstraints(unittest.TestCase):
    """Localized events: EMFI improves but P_stress doesn't breach threshold at peak."""

    P_STRESS_THRESH = 0.50

    @classmethod
    def setUpClass(cls):
        df = _load_taxonomy()
        cls.localized = df[df["category"] == "Localized"].copy()

    def test_localized_not_systemic(self):
        """Localized events should not meet both systemic criteria simultaneously."""
        EMFI_Q75 = 0.548
        both = self.localized[
            (self.localized["p_stress_peak"] >= self.P_STRESS_THRESH) &
            (self.localized["emfi_post_max"] > EMFI_Q75)
        ]
        self.assertEqual(len(both), 0,
                         msg=f"{len(both)} Localized events meet both Systemic criteria (should be 0)")

    def test_localized_mean_emfi_delta_positive(self):
        mean_delta = self.localized["emfi_delta"].mean()
        self.assertGreater(mean_delta, 0,
                           msg=f"Localized mean emfi_delta should be positive (EMFI rises), got {mean_delta:.4f}")


