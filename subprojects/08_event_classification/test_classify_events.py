    def test_covid_march_2020_systemic(self):
        row = self._get_row(date(2020, 3, 3))
        self.assertIsNotNone(row, msg="2020-03-03 (COVID shock) not found in taxonomy")
        self.assertEqual(row["category"], "Systemic",
                         msg=f"COVID shock 2020-03-03 should be Systemic, got {row['category']}")

