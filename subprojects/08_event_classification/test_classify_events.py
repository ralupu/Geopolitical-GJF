class TestFigures(unittest.TestCase):
    """PNG figures must be real image files with non-trivial size."""

    FIGS = ["Fig_EventTimeline.png", "Fig_NetworkCorr_Systemic.png"]
    MIN_SIZE_BYTES = 10_000  # at least 10 KB

    def test_figures_minimum_size(self):
        for fig in self.FIGS:
            path = _path(fig)
            if not os.path.isfile(path):
                self.fail(f"Figure not found: {fig}")
            size = os.path.getsize(path)
            self.assertGreater(size, self.MIN_SIZE_BYTES,
                               msg=f"{fig} is only {size} bytes — may be empty/corrupt")

    def test_figures_png_magic_bytes(self):
        PNG_HEADER = b"\x89PNG\r\n\x1a\n"
        for fig in self.FIGS:
            path = _path(fig)
            if not os.path.isfile(path):
                self.fail(f"Figure not found: {fig}")
            with open(path, "rb") as fh:
                header = fh.read(8)
            self.assertEqual(header, PNG_HEADER,
                             msg=f"{fig} does not start with PNG magic bytes")


