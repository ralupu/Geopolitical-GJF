class TestAnchorEvents(unittest.TestCase):
    """Key geopolitical events must be classified as expected."""

    @classmethod
    def setUpClass(cls):
        cls.df = _load_taxonomy()
        cls.df_indexed = cls.df.set_index("date")

    def _get_row(self, dt: date):
        if dt in self.df_indexed.index:
            return self.df_indexed.loc[dt]
