# 4. Systemic classification constraints
# ===========================================================================
class TestSystemicConstraints(unittest.TestCase):
    """Every Systemic event must satisfy both threshold criteria."""

    EMFI_Q75 = 0.548
    P_STRESS_THRESH = 0.50

    @classmethod
    def setUpClass(cls):
        df = _load_taxonomy()
        cls.systemic = df[df["category"] == "Systemic"].copy()

    def test_systemic_p_stress_peak_gte_threshold(self):
        failing = self.systemic[self.systemic["p_stress_peak"] < self.P_STRESS_THRESH]
        self.assertEqual(len(failing), 0,
                         msg=f"{len(failing)} Systemic events have p_stress_peak < {self.P_STRESS_THRESH}:\n{failing[['date','p_stress_peak']]}")

    def test_systemic_emfi_post_max_gte_q75(self):
        failing = self.systemic[self.systemic["emfi_post_max"] <= self.EMFI_Q75]
        self.assertEqual(len(failing), 0,
                         msg=f"{len(failing)} Systemic events have emfi_post_max <= {self.EMFI_Q75}:\n{failing[['date','emfi_post_max']]}")

    def test_systemic_mean_emfi_delta_positive(self):
        mean_delta = self.systemic["emfi_delta"].mean()
        self.assertGreater(mean_delta, 0,
                           msg=f"Mean emfi_delta for Systemic events should be positive, got {mean_delta:.4f}")


