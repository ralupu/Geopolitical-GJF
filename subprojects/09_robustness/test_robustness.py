# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
RESULTS_DIR = os.path.join(
    os.path.dirname(__file__), "..", "..", "results", "robustness"
)


def _path(filename: str) -> str:
    return os.path.join(RESULTS_DIR, filename)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _load_summary() -> pd.DataFrame:
    return pd.read_csv(_path("robustness_summary.csv"))


def _load_theta() -> pd.DataFrame:
    return pd.read_csv(_path("state_lp_theta.csv"))


def _load_manifest() -> dict:
    with open(_path("manifest.json")) as f:
        return json.load(f)


def _summary_k0(check_id: str, outcome: str = "EMFI") -> pd.Series | None:
    df = _load_summary()
    sub = df[(df["check_id"] == check_id) & (df["outcome"] == outcome) & (df["horizon"] == 0)]
    return sub.iloc[0] if not sub.empty else None


def _theta_k0(check_id: str) -> float | None:
    df = _load_theta()
    sub = df[(df["check_id"] == check_id) & (df["horizon"] == 0) & df["theta"].notna()]
    return float(sub["theta"].iloc[0]) if not sub.empty else None


