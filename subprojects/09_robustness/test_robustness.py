# 5. COVID exclusion (R01)
# ===========================================================================
class TestCOVIDExclusion(unittest.TestCase):
    def test_covid_beta_k0_positive(self):
        row = _summary_k0("R01", "EMFI")
        self.assertIsNotNone(row, msg="COVID exclusion R01 EMFI k=0 not found")
        self.assertGreater(float(row["beta"]), 0,
                           msg=f"COVID excl β_k0 should be positive, got {row['beta']:.4f}")

    def test_covid_nobs_reduced(self):
        """COVID exclusion should reduce sample by ~150–300 trading days."""
        row_base = _summary_k0("R00", "EMFI")
        row_covid = _summary_k0("R01", "EMFI")
        self.assertIsNotNone(row_base)
        self.assertIsNotNone(row_covid)
        reduction = int(row_base["nobs"]) - int(row_covid["nobs"])
        self.assertGreater(reduction, 100, msg=f"COVID excl reduction = {reduction} (expected >100)")
        self.assertLess(reduction, 400,    msg=f"COVID excl reduction = {reduction} (expected <400)")

    def test_covid_pstress_present(self):
        df = _load_summary()
        sub = df[(df["check_id"] == "R01") & (df["outcome"] == "P_stress") & (df["horizon"] == 0)]
        self.assertFalse(sub.empty, msg="COVID excl P_stress k=0 not found")

    def test_covid_tci_present(self):
        df = _load_summary()
        sub = df[(df["check_id"] == "R01") & (df["outcome"] == "tci_w100") & (df["horizon"] == 0)]
        self.assertFalse(sub.empty, msg="COVID excl tci_w100 k=0 not found")

    def test_covid_beta_magnitude_vs_baseline(self):
        """COVID excl β should be somewhat smaller than baseline but same sign."""
        row_base  = _summary_k0("R00", "EMFI")
        row_covid = _summary_k0("R01", "EMFI")
        self.assertIsNotNone(row_base)
        self.assertIsNotNone(row_covid)
        # COVID beta should be positive and less than 2x the baseline
        ratio = float(row_covid["beta"]) / float(row_base["beta"])
        self.assertGreater(ratio, 0,   msg="COVID excl beta should be positive")
        self.assertLess(ratio, 2.0,    msg=f"COVID excl beta ratio={ratio:.2f} vs baseline (unexpected)")


