class TestFigures(unittest.TestCase):
    FIGS = ["Fig_Robustness_LP.png", "Fig_Robustness_StateLPTheta.png"]
    MIN_SIZE = 20_000  # 20 KB
    PNG_HEADER = b"\x89PNG\r\n\x1a\n"

    def test_figures_minimum_size(self):
        for fig in self.FIGS:
            path = _path(fig)
            if not os.path.isfile(path):
                self.fail(f"Figure not found: {fig}")
            size = os.path.getsize(path)
            self.assertGreater(size, self.MIN_SIZE,
                               msg=f"{fig} is only {size} bytes (expected >{self.MIN_SIZE})")

    def test_figures_png_magic_bytes(self):
        for fig in self.FIGS:
            path = _path(fig)
            if not os.path.isfile(path):
                self.fail(f"Figure not found: {fig}")
            with open(path, "rb") as fh:
                header = fh.read(8)
            self.assertEqual(header, self.PNG_HEADER,
                             msg=f"{fig} does not start with PNG magic bytes")


